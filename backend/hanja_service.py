def _load_hanja_table():
    global _REVERSE_HANJA_MAP
    if _REVERSE_HANJA_MAP:
        return

    try:
        # hanja 라이브러리의 table.yml 경로 찾기
        table_path = os.path.join(os.path.dirname(table.__file__), 'table.yml')
        with open(table_path, 'r', encoding='utf-8') as f:
            data = yaml.safe_load(f)
            
            # 한글 -> [한자, 한자, ...] 맵 생성
            for hanja_char, hangul_char in data.items():
                if hangul_char not in _REVERSE_HANJA_MAP:
                    _REVERSE_HANJA_MAP[hangul_char] = []
                _REVERSE_HANJA_MAP[hangul_char].append(hanja_char)
                
    except Exception as e:
        print(f"Hanja table load error: {e}")
        # 실패 시 최소한의 기본 데이터라도 유지
        _REVERSE_HANJA_MAP = {"박": ["朴", "博"], "철": ["哲", "鐵"], "세": ["世", "洗"]}

def get_hanja_candidates(hangul_char):
    """한글 한 글자에 대해 한자 후보 리스트 반환 (우선순위 정렬 적용)"""
    if not _REVERSE_HANJA_MAP:
        _load_hanja_table()
    
    # 1. 별칭 처리 (김 -> 금 등)
    search_char = HANJA_ALIAS.get(hangul_char, hangul_char)
    
    raw_candidates = _REVERSE_HANJA_MAP.get(search_char, [])
    
    # 2. 우선순위 산출
    priority_list = PRIORITY_HANJA.get(hangul_char, [])
    top_priority = TOP_PRIORITY_HANJA.get(hangul_char, [])
    if isinstance(top_priority, str):
        top_priority = [top_priority]
    
    # 3. 정렬 가중치 부여
    # - 가중치 0: 최우선 (TOP_PRIORITY)
    # - 가중치 1: 상용 (PRIORITY)
    # - 가중치 2: 기타
    
    def get_weight(h):
        if h in top_priority: return 0
        if h in priority_list: return 1
        return 2
    
    sorted_candidates = sorted(
        raw_candidates,
        key=lambda x: (get_weight(x), x)
    )
    
    # 상위 50개만 반환 (너무 많으면 UI 부담)
    final_list = sorted_candidates[:50]
    
    return [{"hanja": c, "meaning": ""} for c in final_list]
