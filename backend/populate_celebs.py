MBTI_ESTIMATION_MAP = {
    "비견": "ISTJ", "겁재": "ESTP",
    "식신": "ISFP", "상관": "ENTP",
    "편재": "ESTJ", "정재": "ISTJ",
    "편관": "ENTJ", "정관": "ESTJ",
    "편인": "INTP", "정인": "ISFJ"
}

def estimate_mbti(saju_result):
    """사주 데이터를 기반으로 MBTI 추정"""
    god_count = saju_result.get("god_count", {})
    if not god_count:
        return "Unknown"
    
    # 가장 빈도가 높은 십성 찾기
    dominant_god = max(god_count, key=god_count.get)
    return MBTI_ESTIMATION_MAP.get(dominant_god, "INFP") # 기본값

def estimate_tags(saju_result):
    """사주 데이터를 기반으로 태그 생성"""
    tags = []
    # 오행 강도 기반 태그
    elements = saju_result.get("elements", {})
    strongest = elements.get("strongest")
    if strongest:
        tags.append(f"#{strongest}기운강함")
    
    # 십성 기반 태그
    gods = saju_result.get("ten_gods", {})
    for g in gods.values():
        if g in ["비견", "겁재"]: tags.append("#도화살") # 단순 예시
        if g in ["편관", "정관"]: tags.append("#리더십")
    
    # 중복 제거 및 제한
    return " ".join(list(set(tags))[:3])

def populate():
    update_celeb_schema()
    
    celebs_to_insert = []
    
    for name, cat, rank, bdate, gender, real_mbti, desc in CELEB_DATA_SOURCE:
        # 사주 계산 (기본적으로 12:00 정오 기준)
        try:
            saju = calculate_full_saju(bdate, "12:00")
            
            mbti = real_mbti
            is_estimated = False
            if not mbti:
                mbti = estimate_mbti(saju)
                is_estimated = True
            
            tags = estimate_tags(saju)
            
            celeb = CelebSajuModel(
                name=name,
                category=cat,
                rank=rank,
                birth_date=bdate,
                birth_time="12:00",
                gender=gender,
                mbti=mbti,
                is_mbti_estimated=is_estimated,
                description=desc,
                tags=tags
            )
            celebs_to_insert.append(celeb)
        except Exception as e:
            print(f"Error processing {name}: {e}")
            continue
            
    insert_celebs(celebs_to_insert)

if __name__ == "__main__":
    populate()
